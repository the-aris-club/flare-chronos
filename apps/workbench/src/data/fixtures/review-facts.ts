import type { Fact } from './review';

const PUBLISHED = 'Published figure';

function makeFact(
  key: string,
  value: string,
  unit: string,
  text: string,
  tool: string,
  field: string,
  raw: string,
  provenance: string,
  tolerance: string,
  call: string,
  extra: Partial<Fact> = {},
): Fact {
  return {
    key,
    value,
    unit,
    text,
    tool,
    field,
    raw,
    provenance,
    tolerance,
    call,
    verdict: 'verified',
    ...extra,
  };
}

